import XCTest
@testable import NotchCore

final class ClipboardHistoryTests: XCTestCase {
    private func text(_ value: String, pinned: Bool = false, source: String = "Заметки") -> ClipboardItem {
        ClipboardItem(kind: .text, text: value, sourceName: source, isPinned: pinned)
    }

    func testDuplicateReturnsToFrontWithoutLosingIdentityOrPin() {
        let original = text("запомнить", pinned: true)
        var history = ClipboardHistory()
        history.insert(original)
        history.insert(text("другая запись"))
        history.insert(text("запомнить", source: "Терминал"))
        XCTAssertEqual(history.items.count, 2)
        XCTAssertEqual(history.items[0].id, original.id)
        XCTAssertTrue(history.items[0].isPinned)
        XCTAssertEqual(history.items[0].sourceName, "Терминал")
    }

    func testCountEvictionProtectsPinnedAndRemovesOldestOrdinaryItem() {
        var history = ClipboardHistory(maxItems: 3)
        history.insert(text("закреплено", pinned: true))
        history.insert(text("старое"))
        history.insert(text("среднее"))
        history.insert(text("новое"))
        XCTAssertEqual(history.items.map(\.text), ["новое", "среднее", "закреплено"])
    }

    func testFullPinnedHistoryRejectsIncomingCapture() {
        var history = ClipboardHistory(maxItems: 1)
        history.insert(text("важное", pinned: true))
        XCTAssertFalse(history.insert(text("новое")))
        XCTAssertEqual(history.items.map(\.text), ["важное"])
    }

    func testByteLimitUsesUTF8AndEvictsEvenBelowCountLimit() {
        var history = ClipboardHistory(maxItems: 500, maxBytes: 10)
        history.insert(text("старое"))
        history.insert(text("новое"))
        XCTAssertEqual(history.items.map(\.text), ["новое"])
        XCTAssertEqual(history.totalBytes, 10)
        XCTAssertFalse(history.insert(text("слишком большое")))
        XCTAssertEqual(history.totalBytes, 10)
    }

    func testExplicitSmallerLimitRemainsBoundedWhenEverythingIsPinned() {
        var history = ClipboardHistory()
        history.insert(text("первое", pinned: true))
        history.insert(text("второе", pinned: true))
        history.setLimits(maxItems: 1)
        XCTAssertEqual(history.items.map(\.text), ["второе"])
    }

    func testClearPreservesPinsUnlessExplicitlyIncluded() {
        let saved = text("сохранить", pinned: true)
        var history = ClipboardHistory(items: [text("обычное"), saved])
        history.clear()
        XCTAssertEqual(history.items, [saved])
        history.clear(includePinned: true)
        XCTAssertTrue(history.items.isEmpty)
    }

    func testDedupUsesPayloadAndKeepsKindsDistinct() {
        let image = ClipboardItem(kind: .image, imageData: Data([1, 2, 3]), sourceName: "Фото")
        let files = ClipboardItem(kind: .files, filePaths: ["/tmp/example.png"], sourceName: "Finder")
        var history = ClipboardHistory(items: [text("example.png"), image, files])
        history.insert(ClipboardItem(kind: .image, imageData: Data([1, 2, 3]), sourceName: "Браузер"))
        XCTAssertEqual(history.items.count, 3)
        XCTAssertEqual(history.items.first?.kind, .image)
        XCTAssertEqual(history.items.first?.sourceName, "Браузер")
    }

    func testSearchIncludesWholeTextPathsAndSourceRatherThanOnlyTruncatedTitle() {
        let item = text(String(repeating: "а", count: 300) + " нужное слово", source: "Терминал")
        XCTAssertFalse(item.title.contains("нужное слово"))
        XCTAssertTrue(item.searchText.contains("нужное слово"))
        XCTAssertTrue(item.searchText.contains("Терминал"))
        let files = ClipboardItem(kind: .files, filePaths: ["/архив/чертёж.step"], sourceName: "Finder")
        XCTAssertTrue(files.searchText.contains("/архив/чертёж.step"))
        XCTAssertEqual(files.title, "чертёж.step")
    }

    func testConcealedTransientAndGeneratedMarkersPreventCaptureRegardlessOfCase() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            XCTAssertFalse(ClipboardCapturePolicy.shouldCapture(types: ["public.utf8-plain-text", marker],
                sourceBundleID: "com.example.editor", exclusions: ""))
        }
        XCTAssertTrue(ClipboardCapturePolicy.shouldCapture(types: ["public.png"], sourceBundleID: nil, exclusions: ""))
    }

    func testBundleExclusionsAcceptCommaAndNewlineListsAndIgnoreCase() {
        let excluded = " com.Example.Passwords,\norg.example.private\r\n"
        XCTAssertFalse(ClipboardCapturePolicy.shouldCapture(types: [], sourceBundleID: "COM.EXAMPLE.PASSWORDS", exclusions: excluded))
        XCTAssertFalse(ClipboardCapturePolicy.shouldCapture(types: [], sourceBundleID: "org.example.private", exclusions: excluded))
        XCTAssertTrue(ClipboardCapturePolicy.shouldCapture(types: [], sourceBundleID: "com.example.editor", exclusions: excluded))
        XCTAssertFalse(ClipboardCapturePolicy.shouldCapture(types: [], sourceBundleID: "com.apple.Passwords",
            exclusions: ClipboardCapturePolicy.defaultExcludedBundleIDs))
    }

    func testOversizedAndAmbiguousPayloadsAreNotRetained() {
        XCTAssertFalse(ClipboardCapturePolicy.accepts(text(String(repeating: "x", count: ClipboardCapturePolicy.maxTextBytes + 1))))
        XCTAssertFalse(ClipboardCapturePolicy.accepts(ClipboardItem(kind: .image,
            imageData: Data(count: ClipboardCapturePolicy.maxImageBytes + 1), sourceName: "Фото")))
        XCTAssertFalse(ClipboardCapturePolicy.accepts(ClipboardItem(kind: .text, text: "текст",
            imageData: Data([1]), sourceName: "приложение")))
        XCTAssertFalse(ClipboardCapturePolicy.accepts(ClipboardItem(kind: .files, filePaths: ["relative/path"], sourceName: "Finder")))
    }

    func testRestoredDuplicatesAndOversizedItemsAreValidatedAndBounded() {
        var duplicate = text("одинаковое")
        duplicate.createdAt = Date(timeIntervalSince1970: 0)
        let newer = text("одинаковое", source: "новое приложение")
        let invalid = text(String(repeating: "x", count: ClipboardCapturePolicy.maxTextBytes + 1))
        let history = ClipboardHistory(items: [newer, invalid, duplicate], maxItems: 3)
        XCTAssertEqual(history.items.count, 1)
        XCTAssertEqual(history.items.first?.sourceName, "новое приложение")
    }

    func testBinaryArchiveRoundTripKeepsPinsSourcesAndImageOrFileRepresentations() throws {
        let values = [text("строка\nс Unicode: 🪁", pinned: true),
            ClipboardItem(kind: .image, imageData: Data([1, 2, 3]), sourceName: "Фото"),
            ClipboardItem(kind: .files, filePaths: ["/tmp/a.pdf", "/tmp/b.pdf"], sourceName: "Finder",
                          sourceBundleID: "com.apple.finder", createdAt: Date(timeIntervalSince1970: 100))]
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        let encoded = try encoder.encode(values)
        XCTAssertEqual(try PropertyListDecoder().decode([ClipboardItem].self, from: encoded), values)
    }
}
