import Foundation

public enum ClipboardKind: String, Codable, Sendable {
    case text, image, files
}

public struct ClipboardItem: Identifiable, Codable, Equatable, Sendable {
    public var id: UUID
    public var kind: ClipboardKind
    public var text: String?
    public var imageData: Data?
    public var filePaths: [String]
    public var sourceName: String
    public var sourceBundleID: String?
    public var createdAt: Date
    public var isPinned: Bool

    public init(id: UUID = UUID(), kind: ClipboardKind, text: String? = nil,
                imageData: Data? = nil, filePaths: [String] = [],
                sourceName: String, sourceBundleID: String? = nil,
                createdAt: Date = Date(), isPinned: Bool = false) {
        self.id = id
        self.kind = kind
        self.text = text
        self.imageData = imageData
        self.filePaths = filePaths
        self.sourceName = sourceName
        self.sourceBundleID = sourceBundleID
        self.createdAt = createdAt
        self.isPinned = isPinned
    }

    public var title: String {
        switch kind {
        case .text:
            let preview = String((text ?? "").prefix(200))
                .replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\r", with: " ")
                .trimmingCharacters(in: .whitespacesAndNewlines)
            return preview.isEmpty ? "пробелы и переносы строк" : preview
        case .image:
            return "изображение"
        case .files:
            let first = filePaths.first.map { URL(fileURLWithPath: $0).lastPathComponent } ?? "файл"
            return filePaths.count > 1 ? "\(first) и ещё \(filePaths.count - 1)" : first
        }
    }

    public var searchText: String {
        [text ?? "", filePaths.joined(separator: "\n"), sourceName, sourceBundleID ?? ""]
            .joined(separator: "\n")
    }

    public var byteCount: Int {
        switch kind {
        case .text: return text?.utf8.count ?? 0
        case .image: return imageData?.count ?? 0
        case .files: return filePaths.reduce(0) { $0 + $1.utf8.count }
        }
    }

    public func hasSameContent(as other: ClipboardItem) -> Bool {
        guard kind == other.kind else { return false }
        switch kind {
        case .text: return text == other.text
        case .image: return imageData == other.imageData
        case .files: return filePaths == other.filePaths
        }
    }
}

public enum ClipboardCapturePolicy {
    public static let maxTextBytes = 1_048_576
    public static let maxImageBytes = 8_388_608
    public static let maxFileReferences = 4096
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.concealedtype", "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype", "de.petermaurer.transientpasteboardtype",
        "com.typeit4me.clipping", "pasteboard generator type", "com.agilebits.onepassword",
        "app.notchdeck.clipboard"
    ]
    public static let defaultExcludedBundleIDs = [
        "com.1password.1password", "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "com.keepassxc.keepassxc",
        "com.dashlane.Dashlane", "com.lastpass.LastPass", "com.apple.Passwords"
    ].joined(separator: "\n")

    public static func excludedIDs(from value: String) -> Set<String> {
        Set(value.components(separatedBy: CharacterSet(charactersIn: ",\n\r"))
            .map { $0.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() }
            .filter { !$0.isEmpty })
    }

    public static func shouldCapture(types: [String], sourceBundleID: String?, exclusions: String) -> Bool {
        guard ignoredTypes.isDisjoint(with: types.map { $0.lowercased() }) else { return false }
        guard let sourceBundleID else { return true }
        return !excludedIDs(from: exclusions).contains(sourceBundleID.lowercased())
    }

    public static func accepts(_ item: ClipboardItem) -> Bool {
        switch item.kind {
        case .text:
            return item.imageData == nil && item.filePaths.isEmpty
                && !(item.text?.isEmpty ?? true) && item.byteCount <= maxTextBytes
        case .image:
            return item.text == nil && item.filePaths.isEmpty
                && !(item.imageData?.isEmpty ?? true) && item.byteCount <= maxImageBytes
        case .files:
            return item.text == nil && item.imageData == nil && !item.filePaths.isEmpty
                && item.filePaths.count <= maxFileReferences && item.byteCount <= maxTextBytes
                && item.filePaths.allSatisfy { $0.hasPrefix("/") && !$0.contains("\0") }
        }
    }
}

public struct ClipboardHistory: Sendable {
    public static let defaultMaxBytes = 64 * 1_048_576
    public private(set) var items: [ClipboardItem] = []
    public private(set) var maxItems: Int
    public private(set) var maxBytes: Int
    public var totalBytes: Int { items.reduce(0) { $0 + $1.byteCount } }

    public init(items: [ClipboardItem] = [], maxItems: Int = 500,
                maxBytes: Int = ClipboardHistory.defaultMaxBytes) {
        self.maxItems = max(1, maxItems)
        self.maxBytes = max(0, maxBytes)
        for item in items.reversed() { insert(item) }
    }

    @discardableResult
    public mutating func insert(_ candidate: ClipboardItem) -> Bool {
        guard ClipboardCapturePolicy.accepts(candidate), candidate.byteCount <= maxBytes else { return false }
        var candidate = candidate
        if let existing = items.firstIndex(where: { $0.hasSameContent(as: candidate) }) {
            candidate.id = items[existing].id
            candidate.isPinned = candidate.isPinned || items[existing].isPinned
            items.remove(at: existing)
        }
        items.insert(candidate, at: 0)
        trim()
        return items.contains { $0.id == candidate.id }
    }

    public mutating func setLimits(maxItems: Int, maxBytes: Int = ClipboardHistory.defaultMaxBytes) {
        self.maxItems = max(1, maxItems)
        self.maxBytes = max(0, maxBytes)
        trim()
    }

    public mutating func togglePin(id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
    }

    public mutating func remove(id: UUID) { items.removeAll { $0.id == id } }
    public mutating func clear(includePinned: Bool = false) {
        items.removeAll { includePinned || !$0.isPinned }
    }

    private mutating func trim() {
        while items.count > maxItems || totalBytes > maxBytes {
            // При уменьшении лимита закреплённые записи вытесняются последними.
            let index = items.lastIndex(where: { !$0.isPinned }) ?? items.indices.last!
            items.remove(at: index)
        }
    }
}
